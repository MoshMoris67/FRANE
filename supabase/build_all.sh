#!/usr/bin/env bash
# Concatenates every migration, in order, into supabase/all_migrations.sql — one file to paste into the Supabase SQL editor.
set -e
cd "$(dirname "$0")"
out=all_migrations.sql
{ echo "-- FRANE CONCRETE FACTORY — complete database schema (generated by supabase/build_all.sh; do not edit)."
  echo "-- Run once on a NEW Supabase project. Later upgrades: run only the new numbered files from supabase/migrations/."
  for f in migrations/*.sql; do echo; echo "-- ====================================================================="; echo "-- FILE: $f"; echo "-- ====================================================================="; cat "$f"; done; } > "$out"
echo "wrote supabase/$out ($(wc -l < "$out") lines)"
